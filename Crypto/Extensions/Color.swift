import Foundation
import SwiftUI

extension Color {
    static let theme = ColorTheme()
}

struct ColorTheme {
    let accent = Color("AccentColor")
    let background = Color("BackgroundColor")
    let green = Color("themeGreen")
    let red = Color("themeRed")
    let secondaryText = Color("SecondaryTextColor")
}


